"""Component-sizing report (Q5) from the experiment time-history metrics.

Reads results.parquet of experiments 001, 002, 004 (whatever exists) and
writes reports/component_sizing.md: sprag torque envelope and engagements
per km (for Formsprag), flywheel inertia vs speed ripple, generator
speed/torque envelope, bias-spring stroke and stop rates by road class.
Every number is `modeled`; conditions are carried on every row.
"""

from __future__ import annotations

import pathlib

import numpy as np
import pandas as pd

ROOT = pathlib.Path(__file__).resolve().parents[1]
EXP = ROOT / "experiments"
OUT = ROOT / "reports" / "component_sizing.md"


def _load(name):
    p = EXP / name / "results" / "results.parquet"
    if not p.exists():
        return None
    df = pd.read_parquet(p)
    df = df[df["error"].isna()] if "error" in df else df
    g = df[df["is_gate"]].copy()
    if "c_s_scale" not in g:
        g["c_s_scale"] = 1.0
    g["c_s_scale"] = g["c_s_scale"].fillna(1.0)
    g["Jr"] = g["gate_J"] * g["gate_r"] ** 2
    g["mph"] = (g["speed"] * 2.237).round(0)
    return g


def q(s, p):
    return float(np.nanpercentile(s, p)) if len(s) else np.nan


def tbl(df, cols, fmt):
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        cells = []
        for c in cols:
            v = r[c]
            cells.append(fmt.get(c, "{:.3g}").format(v) if isinstance(v, (float, np.floating)) else str(v))
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def main():
    out = ["# Component sizing (modeled; auto-generated by reports/component_sizing.py)", "",
           "All values are time-history statistics from the experiments named; conditions on every row. "
           "Tag: modeled. Torques are at the rotor (generator) shaft; multiply by r to get the axial force on the drive rod.", ""]
    e2 = _load("002_roads_speeds_vehicles")
    e1 = _load("001_midsize_isoC_60mph_load_sweep")
    e4 = _load("004_transmission_ratio")
    e6 = _load("006_flywheel_tornado")

    # 1. Sprag: torque envelope and engagement counts per km, best load per vehicle/class/speed
    src = e2 if e2 is not None else e1
    if src is not None:
        best = src.loc[src.groupby(["vehicle", "klass", "mph", "c_s_scale"])["P_elec"].idxmax()] if "vehicle" in src else src
        agg = (best.groupby(["vehicle", "klass", "mph", "c_s_scale"])
               .agg(r=("gate_r", "first"), J=("gate_J", "first"), c_gen=("c_gen", "first"),
                    P_elec=("P_elec", "median"), N_eng_A_km=("N_eng_A_per_km", "median"),
                    N_eng_B_km=("N_eng_B_per_km", "median"), T_c_p99=("T_c_p99", "median"),
                    T_c_max=("T_c_max", "max"), impulse_max=("impulse_max", "max"),
                    race_rpm_max=("race_rpm_max", "max"), engaged_frac=("engaged_frac", "median"))
               .reset_index())
        agg["engagements_per_1e6_km"] = (agg["N_eng_A_km"] + agg["N_eng_B_km"]) * 1e6
        agg["km_to_1e6_cycles_per_clutch"] = 1e6 / agg[["N_eng_A_km", "N_eng_B_km"]].max(axis=1)
        out += ["## 1. Sprag clutches (Formsprag input)", "",
                "Engagements per km per clutch set (A = collapse stroke, B = expansion stroke), transmitted torque "
                "99th percentile and max at the rotor, lock-up impulse (0 when backlash = 0), race speed vs catalog "
                "lift-off (1200 rpm mid-range), and km to 10^6 engagements of the busier clutch.", "",
                tbl(agg, ["vehicle", "klass", "mph", "c_s_scale", "r", "J", "c_gen", "P_elec", "N_eng_A_km", "N_eng_B_km",
                          "T_c_p99", "T_c_max", "race_rpm_max", "engaged_frac", "km_to_1e6_cycles_per_clutch"],
                    {"r": "{:.0f}", "J": "{:.0e}", "c_gen": "{:.3g}", "P_elec": "{:.1f}", "N_eng_A_km": "{:.0f}",
                     "N_eng_B_km": "{:.0f}", "T_c_p99": "{:.2f}", "T_c_max": "{:.2f}", "race_rpm_max": "{:.0f}",
                     "engaged_frac": "{:.2f}", "km_to_1e6_cycles_per_clutch": "{:.0f}", "mph": "{:.0f}", "c_s_scale": "{:g}"}),
                "", "Reading: engagement counts are set by the road's zero-crossing rate (roughly the body-mode "
                "frequency), not by the load; the torque envelope scales with c_gen·ω. If the catalog rating basis "
                "is 10^6 full-torque cycles (not verified, 04_prior_art item 6), the km column is the service "
                "interval at catalog torque; size the clutch so T_c_p99 is well below catalog torque with an "
                "indexing service factor of 2–6.", ""]

    # 2. Flywheel: speed ripple vs J (exp 006 if present, else exp 001 J corners)
    src = e6 if e6 is not None else e1
    if src is not None:
        cols = ["gate_J", "gate_r"]
        agg = (src.groupby(cols).agg(Jr=("Jr", "first"), rpm_mean=("rpm_mean", "median"), rpm_p05=("rpm_p05", "median"),
                                     rpm_p95=("rpm_p95", "median"), ripple=("rpm_ripple_frac", "median"),
                                     engaged=("engaged_frac", "median"), P_elec=("P_elec", "median"),
                                     frac_1600=("frac_above_1600rpm", "median")).reset_index())
        out += ["## 2. Flywheel inertia vs shaft-speed ripple", "",
                "ripple = std(rpm)/mean(rpm) over the stationary window; engaged = fraction of time a clutch is "
                "locked; frac_1600 = fraction of time above a claw-pole alternator cut-in (1600 rpm).", "",
                tbl(agg, ["gate_J", "gate_r", "Jr", "P_elec", "rpm_mean", "rpm_p05", "rpm_p95", "ripple", "engaged", "frac_1600"],
                    {"gate_J": "{:.0e}", "gate_r": "{:.0f}", "Jr": "{:.1f}", "P_elec": "{:.1f}", "rpm_mean": "{:.0f}",
                     "rpm_p05": "{:.0f}", "rpm_p95": "{:.0f}", "ripple": "{:.2f}", "engaged": "{:.2f}", "frac_1600": "{:.2f}"}),
                "", "Reading: J trades ripple against reflected inertance J r² on the stroke (F2). A claw-pole "
                "alternator needs frac_1600 ≈ 1 to make anything; at the low-r points it never gets there, which is "
                "why the generator must be a PM machine wound for the actual speed band.", ""]

    # 3. Generator envelope
    src = e2 if e2 is not None else e1
    if src is not None:
        src = src.copy()
        src["T_gen_p95"] = src["c_gen"] * src["rpm_p95"] * 2 * np.pi / 60
        agg = (src.groupby(["vehicle", "klass", "mph"]).agg(rpm_p95=("rpm_p95", "max"), rpm_max=("rpm_max", "max"),
                                                            T_gen_p95=("T_gen_p95", "max"), P_elec_max=("P_elec", "max")).reset_index())
        out += ["## 3. Generator speed / torque envelope (over all loads tried)", "",
                tbl(agg, ["vehicle", "klass", "mph", "rpm_p95", "rpm_max", "T_gen_p95", "P_elec_max"],
                    {"rpm_p95": "{:.0f}", "rpm_max": "{:.0f}", "T_gen_p95": "{:.2f}", "P_elec_max": "{:.1f}", "mph": "{:.0f}"}),
                "", "Reading: the machine must make its rated power at a few hundred to ~1500 rpm with torque of "
                "order 0.1–1 N·m at r = 300 rad/m; raising r raises speed and lowers torque but raises J r² (F2).", ""]

    # 4. Bias spring stroke and stops by class
    if e2 is not None:
        best = e2.loc[e2.groupby(["vehicle", "klass", "mph", "c_s_scale"])["P_elec"].idxmax()]
        agg = (best.groupby(["vehicle", "klass", "mph", "c_s_scale"])
               .agg(x_b_rms=("x_b_rms", "median"), x_b_max=("x_b_max", "max"), x_b_min=("x_b_min", "min"),
                    t_stop=("t_stop_frac", "median"), N_stop_comp_km=("N_stop_comp_per_km", "median"),
                    N_stop_ext_km=("N_stop_ext_per_km", "median")).reset_index())
        out += ["## 4. Bias-spring stroke and hard-stop rates (travel 4 in centred, k_b/k_m = 1/8.35)", "",
                tbl(agg, ["vehicle", "klass", "mph", "c_s_scale", "x_b_rms", "x_b_max", "x_b_min", "t_stop", "N_stop_comp_km", "N_stop_ext_km"],
                    {"x_b_rms": "{:.4f}", "x_b_max": "{:.4f}", "x_b_min": "{:.4f}", "t_stop": "{:.3f}",
                     "N_stop_comp_km": "{:.1f}", "N_stop_ext_km": "{:.1f}", "mph": "{:.0f}", "c_s_scale": "{:g}"}),
                "", "Reading: see experiment 005 for the ratio × travel map; stops become frequent on class D and "
                "when the damper is reduced (larger strokes).", ""]
    if e4 is not None:
        agg = (e4.groupby(["gate_J", "gate_r"]).agg(Jr=("Jr", "first"), race_rpm_max=("race_rpm_max", "max"),
                                                    margin=("race_rpm_margin_vs_liftoff", "min"),
                                                    P_elec=("P_elec", "max")).reset_index())
        out += ["## 5. Race speed vs sprag lift-off across the ratio sweep (exp 004)", "",
                tbl(agg, ["gate_J", "gate_r", "Jr", "P_elec", "race_rpm_max", "margin"],
                    {"gate_J": "{:.0e}", "gate_r": "{:.0f}", "Jr": "{:.1f}", "P_elec": "{:.1f}", "race_rpm_max": "{:.0f}", "margin": "{:.0f}"}),
                "", "Reading: with the sprags on the high-speed side of the ratio, r above ~800 rad/m puts peak race "
                "speed above catalog lift-off on class C at 60 mph; put the clutches on the low-speed side and gear "
                "up after rectification, or confirm a lift-off-free sprag type (GMN FE 8000 class).", ""]
    OUT.write_text("\n".join(out) + "\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
