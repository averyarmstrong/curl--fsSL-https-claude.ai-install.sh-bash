"""Experiment 001: generator-load sweep, mid-size car, ISO C, 60 mph. See config.yaml and README.md."""
import argparse
import pathlib
import sys

import pandas as pd
import yaml

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[2] / "src"))
from aks_lab.sweeps.runner import run_sweep  # noqa: E402
from aks_lab.validate.analytic import mean_road_power  # noqa: E402
from aks_lab.vehicles import corner  # noqa: E402
from aks_lab.viz.plots import md_table, plot_band, plt, save  # noqa: E402

HERE = pathlib.Path(__file__).resolve().parent
CFG = yaml.safe_load((HERE / "config.yaml").read_text())
OUT = HERE / "results"


def cases():
    base = dict(vehicle=CFG["vehicle"], klass=CFG["klass"], speed=CFG["speed_mps"],
                duration=CFG["duration_s"], damper_span=CFG["damper_span"], m_f=CFG["m_f_kg"])
    cs = []
    for seed in CFG["seeds"]:
        cs.append({**base, "seed": seed, "gate": None, "tag": "passive"})
        for r in CFG["r"]:
            for J in CFG["J"]:
                for cg in CFG["c_gen"]:
                    cs.append({**base, "seed": seed, "tag": "gate",
                               "gate": {"c_gen": cg, "r": r, "J": J, "k_b_over_k_m": CFG["k_b_over_k_m"],
                                        "travel": CFG["travel_m"]}})
        for r, J in CFG.get("c_s_scale_configs", []):
            for sc in CFG.get("c_s_scale", []):
                if sc == 1.0:
                    continue
                for cg in CFG["c_gen"]:
                    cs.append({**base, "seed": seed, "tag": "gate", "c_s_scale": sc,
                               "gate": {"c_gen": cg, "r": r, "J": J, "k_b_over_k_m": CFG["k_b_over_k_m"],
                                        "travel": CFG["travel_m"]}})
    return cs


def analyse(df: pd.DataFrame):
    df = df[df["error"].isna()] if "error" in df else df
    pas = df[~df["is_gate"]].set_index("seed")
    g = df[df["is_gate"]].copy()
    for col, new in (("a_w_rms", "d_a_w_rms"), ("sws_rms", "d_sws_rms"), ("dtl_rms_frac", "d_dtl_rms_frac"),
                     ("a_s_rms", "d_a_s_rms")):
        g[new] = g[col].values - pas.loc[g["seed"], col].values
        g[new + "_pct"] = 100 * g[new] / pas.loc[g["seed"], col].values
    g["Jr"] = g["gate_J"] * g["gate_r"] ** 2
    if "c_s_scale" not in g:
        g["c_s_scale"] = 1.0
    g["c_s_scale"] = g["c_s_scale"].fillna(1.0)
    g["config"] = g.apply(lambda r: f"r={r.gate_r:.0f}, J={r.gate_J:.0e} (Jr={r.Jr:.0f} kg), damper x{r.c_s_scale:g}", axis=1)
    c, gm = corner(CFG["vehicle"])
    exact = mean_road_power(c, CFG["klass"], CFG["speed_mps"])
    fig, axs = plt.subplots(2, 3, figsize=(13, 7))
    for ax, y in zip(axs.flat, ["P_elec", "phi", "P_net", "d_a_w_rms_pct", "d_dtl_rms_frac_pct", "t_stop_frac"]):
        plot_band(ax, g, "c_gen", y, group="config", logx=True)
        if y == "P_elec":
            ax.axhline(exact["P_road"], color="k", ls="--", lw=0.8, label="road supply k_t W_v/4")
            ax.axhline(pas["P_damper"].mean(), color="gray", ls=":", lw=0.8, label="passive damper")
    axs[0, 0].legend(fontsize=6)
    axs[1, 0].set_ylabel("ISO 2631 W_k accel delta vs passive [%]")
    axs[1, 1].set_ylabel("dyn. tire load RMS delta vs passive [%]")
    fig.suptitle(f"Exp 001 — {CFG['vehicle']}, ISO {CFG['klass']}, {CFG['speed_mps']*2.237:.0f} mph, "
                 f"k_b/k_m={CFG['k_b_over_k_m']}, travel {CFG['travel_m']*39.37:.1f} in; bands = 5-95% over seeds")
    save(fig, OUT / "fig_load_sweep.png", CFG, "exp001 load sweep")

    fig, axs = plt.subplots(1, 3, figsize=(13, 3.6))
    for ax, y in zip(axs, ["x_b_rms", "rpm_mean", "N_eng_A_per_km"]):
        plot_band(ax, g, "c_gen", y, group="config", logx=True)
    axs[0].axhline(CFG["travel_m"] / 2, color="k", ls="--", lw=0.8, label="stop")
    axs[0].legend(fontsize=6)
    save(fig, OUT / "fig_frame_rotor.png", CFG, "exp001 frame stroke, rotor speed, engagements")

    summ = (g.groupby(["config", "c_gen"])
            .agg(P_road=("P_road", "median"), P_elec=("P_elec", "median"), P_elec_lo=("P_elec", "min"),
                 P_elec_hi=("P_elec", "max"), phi=("phi", "median"), P_net=("P_net", "median"),
                 damper_share=("damper_share", "median"), d_a_w_pct=("d_a_w_rms_pct", "median"),
                 d_dtl_pct=("d_dtl_rms_frac_pct", "median"), t_stop=("t_stop_frac", "median"),
                 x_b_rms=("x_b_rms", "median"), rpm=("rpm_mean", "median"),
                 closure=("closure", "max"))
            .reset_index())
    summ.to_csv(OUT / "summary.csv", index=False)
    best = summ.loc[summ.groupby("config")["P_elec"].idxmax()]
    lines = ["## Results (auto-generated by run.py)", "",
             f"Road supply (theorem, exact): **{exact['P_road']:.1f} W per corner**; passive damper dissipates "
             f"{pas['P_damper'].mean():.1f} W (sim, mean of {len(pas)} seeds); passive W_k accel "
             f"{pas['a_w_rms'].mean():.3f} m/s², DTL {pas['dtl_rms_frac'].mean():.3f}.", "",
             "### Best load per (r, J) configuration", "",
             md_table(best, ["config", "c_gen", "P_elec", "P_elec_lo", "P_elec_hi", "phi", "P_net", "damper_share",
                             "d_a_w_pct", "d_dtl_pct", "t_stop", "x_b_rms", "rpm", "closure"],
                      {"c_gen": "{:.4g}", "P_elec": "{:.1f}", "P_elec_lo": "{:.1f}", "P_elec_hi": "{:.1f}",
                       "phi": "{:.3f}", "P_net": "{:.1f}", "d_a_w_pct": "{:+.1f}", "d_dtl_pct": "{:+.1f}",
                       "closure": "{:.1e}"}),
             "", "### Full sweep (median over seeds)", "",
             md_table(summ, ["config", "c_gen", "P_elec", "phi", "P_net", "d_a_w_pct", "d_dtl_pct", "t_stop", "rpm"],
                      {"c_gen": "{:.4g}", "P_elec": "{:.1f}", "phi": "{:.3f}", "P_net": "{:.1f}",
                       "d_a_w_pct": "{:+.1f}", "d_dtl_pct": "{:+.1f}"})]
    (OUT / "RESULTS.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines[:8]))
    return summ


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--workers", type=int, default=None)
    ap.add_argument("--analyse-only", action="store_true")
    a = ap.parse_args()
    if a.analyse_only:
        df = pd.read_parquet(OUT / "results.parquet")
    else:
        df = run_sweep(cases(), OUT, workers=a.workers)
    analyse(df)
